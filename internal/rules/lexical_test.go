func lexicalIDs(src string) map[string]int {
	target := model.TargetFile{Path: "SKILL.md", Language: model.LangMarkdown}
	got := map[string]int{}
	for _, f := range InspectInstructionText(target, model.LangMarkdown, []byte(src)) {
		got[f.RuleID]++
	}
	for _, f := range InspectSkillStructure(target, []byte(src)) {
		got[f.RuleID]++
	}
	return got
}

